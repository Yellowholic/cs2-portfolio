num = 10
while num >= 1:
    print(num)
    num -= 1

print("Time is up!")

# Num is equal to 10 so 10 is the starting point of the loop.
# while num >= 1 is what checks if the number is alreadu below 1. Then it will print the number then subtract 1, and the process repeats until the number reaches the value of 1. 
